"""Readiness score and the plain-text, Markdown and JSON reports."""

from __future__ import annotations

import json
from collections import Counter
from dataclasses import dataclass
from datetime import date

from tuxready import __version__
from tuxready.models import Result, Verdict

ORDER = list(Verdict)


@dataclass
class Score:
    percent: int | None  # None when nothing could be rated
    counts: Counter
    rated: int
    total: int

    @property
    def headline(self) -> str:
        if self.percent is None:
            return "Not enough information for a score yet"
        return f"{self.percent}% ready for Linux"

    @property
    def mood(self) -> str:
        if self.percent is None:
            return ""
        if self.percent >= 90:
            return "You're ready. Go for it!"
        if self.percent >= 70:
            return "Mostly ready: a few things need alternatives or tweaks."
        if self.percent >= 40:
            return "Doable, but plan for some changes, or dual-boot for a while."
        return "Several blockers. Consider dual-booting, or wait a bit."


def score(results: list[Result]) -> Score:
    counts = Counter(r.verdict for r in results)
    rated = [r for r in results if r.verdict.weight is not None]
    if not rated:
        return Score(None, counts, 0, len(results))
    total = sum(r.verdict.weight for r in rated)  # type: ignore[misc]
    return Score(round(100 * total / len(rated)), counts, len(rated), len(results))


def sort_results(results: list[Result]) -> list[Result]:
    """Problems first, so the things that need attention are at the top."""
    priority = {
        Verdict.BLOCKED: 0,
        Verdict.ALTERNATIVE: 1,
        Verdict.TWEAKS: 2,
        Verdict.UNKNOWN: 3,
        Verdict.WORKS: 4,
        Verdict.NATIVE: 5,
        Verdict.NOT_NEEDED: 6,
    }
    return sorted(results, key=lambda r: (priority[r.verdict], r.item.name.lower()))


def counts_line(s: Score) -> str:
    return "   ".join(f"{v.icon} {v.label}: {s.counts[v]}" for v in ORDER if s.counts[v])


def plain(results: list[Result]) -> str:
    s = score(results)
    lines = [f"tuxready: {s.headline}", s.mood, counts_line(s), ""]
    current = None
    for result in sort_results(results):
        if result.verdict is not current:
            current = result.verdict
            lines += ["", f"{current.icon} {current.label.upper()}"]
        kind = result.item.kind.value if result.item.kind else "?"
        lines.append(f"  • {result.item.name} [{kind}] — {result.summary}")
        if result.alternatives:
            lines.append(f"      Try: {', '.join(result.alternatives)}")
        if result.how_to and result.verdict is not Verdict.NATIVE:
            lines.append(f"      How: {result.how_to}")
        elif result.how_to:
            lines.append(f"      Install: {result.how_to}")
    return "\n".join(lines).strip() + "\n"


def markdown(results: list[Result]) -> str:
    s = score(results)
    out = [
        f"# My Linux readiness: {s.percent if s.percent is not None else '?'}%",
        "",
        f"*{s.mood}*" if s.mood else "",
        "",
        f"{counts_line(s)}",
        "",
        "| | Name | Type | Verdict | Notes |",
        "|---|---|---|---|---|",
    ]
    for r in sort_results(results):
        notes = r.summary
        if r.alternatives:
            notes += " **Try:** " + ", ".join(r.alternatives)
        first_link = f" [{r.links[0].title}]({r.links[0].url})" if r.links else ""
        kind = r.item.kind.value if r.item.kind else ""
        out.append(
            f"| {r.verdict.icon} | {_md(r.item.name)} | {kind} | {r.verdict.label} | "
            f"{_md(notes)}{first_link} |"
        )
    out += [
        "",
        f"Generated by [tuxready](https://github.com/Hanocybous/tuxready) {__version__} "
        f"on {date.today().isoformat()}.",
    ]
    return "\n".join(out) + "\n"


def to_json(results: list[Result]) -> str:
    s = score(results)
    return (
        json.dumps(
            {
                "tuxready": __version__,
                "score": s.percent,
                "counts": {v.value: s.counts[v] for v in ORDER},
                "results": [r.to_dict() for r in sort_results(results)],
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n"
    )


def _md(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")
